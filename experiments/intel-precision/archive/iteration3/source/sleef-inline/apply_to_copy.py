"""Prepare an isolated AVX512-only inline-SLEEF row helper and provenance."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ARCHIVE_SHA256 = 'af60856abac08a3b5e72a8d156dd71fec1f7ac23de8ee67793f45f9edcdf0908'
SLEEF_COMMIT = '906ca7512ee483296780a81a21b9ca715d40dfe1'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--row-source', type=Path, required=True)
    parser.add_argument('--row-sha256', required=True)
    parser.add_argument('--generated-header', type=Path, required=True)
    parser.add_argument('--generated-header-sha256', required=True)
    parser.add_argument('--sleef-source-archive', type=Path, required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    paths = [args.row_source.resolve(), args.generated_header.resolve(),
             args.sleef_source_archive.resolve(), here/'sleef_inline_avx512.h',
             here/'check_sine.cpp', Path(__file__).resolve()]
    frozen = {p: p.read_bytes() for p in paths}
    row, header, archive, wrapper, checker, script = (frozen[p] for p in paths)
    if sha(row) != args.row_sha256 or sha(header) != args.generated_header_sha256:
        raise ValueError('Explicit row or generated-header hash mismatch')
    if sha(archive) != ARCHIVE_SHA256:
        raise ValueError('Pinned upstream SLEEF 3.9.0 source archive mismatch')
    hs = header.decode('utf-8')
    if ('generated by SLEEF 3.9.0' not in hs or
            'SLEEFINLINE_AVX512F_H_INCLUDED' not in hs or
            not re.search(r'\bSleef_sinf16_u10avx512f\s*\(', hs) or
            '_mm512_fmadd_ps' not in hs):
        raise ValueError('Expected upstream-generated AVX512F CONFIG1 u10 header')
    source = row.decode('utf-8')
    declaration = 'ROW_AVX512 extern __m512 Sleef_sinf16_u10avx512f(__m512);\n}'
    old = 'const __m512 s=Sleef_sinf16_u10avx512f(_mm512_mul_ps(av,v));'
    if source.count(declaration) != 1 or source.count(old) != 1:
        raise ValueError('Expected one unchanged public declaration and 16-lane Snake call')
    modified = source.replace(declaration, declaration+'\n#include "sleef_inline_avx512.h"', 1)
    modified = modified.replace(old, 'const __m512 s=ip3_sleef_inline_sinf16_u10avx512f(_mm512_mul_ps(av,v));', 1)
    # Restore both edits to prove that no arithmetic, history, tail, or other
    # source text changed accidentally.
    restored = modified.replace(declaration+'\n#include "sleef_inline_avx512.h"', declaration, 1)
    restored = restored.replace('const __m512 s=ip3_sleef_inline_sinf16_u10avx512f(_mm512_mul_ps(av,v));', old, 1)
    if restored != source or any(p.read_bytes() != data for p, data in frozen.items()):
        raise ValueError('Input mutation or unexpected source edit')
    output = args.output_dir.resolve()
    if output.exists():
        raise ValueError('Use a fresh isolated output directory')
    output.mkdir(parents=True)
    outputs = {'row_nonlinear.h': modified.encode(), 'sleefinline_avx512f.h': header,
               'sleef_inline_avx512.h': wrapper, 'check_sine.cpp': checker}
    for name, data in outputs.items():
        (output/name).write_bytes(data)
    manifest = {
        'status': 'source_prepared', 'compiled': False, 'inference_executed': False,
        'sleef_version': '3.9.0', 'sleef_commit': SLEEF_COMMIT,
        'sleef_source_archive_sha256': ARCHIVE_SHA256,
        'source_row_sha256': sha(row), 'generated_header_sha256': sha(header),
        'wrapper_sha256': sha(wrapper), 'checker_sha256': sha(checker),
        'patch_script_sha256': sha(script),
        'outputs': {name: sha(data) for name, data in outputs.items()},
        'changes': ['Include the isolated target-scoped generated-header wrapper',
                    'Replace only the 16-lane external u10 sine call with the private inline definition'],
        'required_flags': ['-fno-fast-math', '-ffp-contract=off'],
        'scope': 'GCC x86_64 AVX512F CONFIG1 only; original CPU guards, 8/4/padded tails, Snake order and history unchanged',
        'required_validation': ['Pinned archive versus inline sine bit parity',
                                'Existing check_rows with modified helper',
                                'Exact full-decoder waveform and causal gates before timing'],
        'generation_note': 'The supplied header hash and archive hash are pinned; retain the separate upstream CMake generation record as provenance. Header text alone does not prove its origin.',
    }
    (output/'source-provenance.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(json.dumps(manifest))


if __name__ == '__main__':
    main()
