"""Seal fresh source identities and a first already-qualified cached shard.

CPU metadata/tensor copies only. New full-source teacher pairs are generated by
a separate producer; no downloaded audio or old target is changed here.
"""
from __future__ import annotations
import argparse
from collections import Counter,defaultdict,deque
import hashlib,heapq,json,math,os,importlib.util,sys
from pathlib import Path

os.environ.setdefault('CUDA_VISIBLE_DEVICES','')
import torch
import run_pilot as base

VERSION='audiovae2_group_continuation_sources_v1'
PAIR_VERSION='audiovae2_group_continuation_pairs_v1'
R9=Path('/workspace/fast-audiovae-convnext-20260909-r9')
P=Path('/workspace/fast-audiovae-compression-20260910-v1')
KEYS=('source_id','audio_sha256','parent_recording_id')
SEED='20260910-wholegroup-unique-continuation-v1'
_spec=importlib.util.spec_from_file_location('compression_manifest_rows',R9/'audiovae_student/data.py')
_data=importlib.util.module_from_spec(_spec);sys.modules[_spec.name]=_data;_spec.loader.exec_module(_data)
ManifestRow=_data.ManifestRow

def digest(value):return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':'),allow_nan=False).encode()).hexdigest()
def rank(s):return hashlib.sha256((SEED+'|'+s).encode()).hexdigest()
def lines(path):return [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]
def read(path):return json.loads(Path(path).read_text())

def main():
 p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True);p.add_argument('--shards',type=Path,required=True);args=p.parse_args()
 if args.out.exists() or args.shards.exists():raise FileExistsError('Use new source-plan and shard paths')
 torch.set_num_threads(1)
 if torch.cuda.is_available():raise RuntimeError('CPU-only plan preparation requires hidden CUDA')
 original_path=P/'pilot-selection-v1.json'; original=read(original_path)
 preflight=read(P/'pilot/preflight.json')
 if base.sha(original_path)!=preflight['identity']['manifest_sha256']:raise ValueError('Original manifest changed')
 inputs={str(original_path):base.sha(original_path),str(P/'pilot/preflight.json'):base.sha(P/'pilot/preflight.json'),str(_data.__file__):base.sha(_data.__file__)}
 def pin(path,expected=None):
  value=base.sha(path)
  if expected and value!=expected:raise ValueError('Source provenance changed: '+str(path))
  inputs[str(path)]=value
  return path
 blocked={k:set() for k in KEYS}
 def block(row):
  for k in KEYS:
   if row.get(k):blocked[k].add(row[k])
 for split in original['splits'].values():
  for row in split['rows']:block(row['manifest_row'])
 reserved=[R9/'data/recipe-v2/optimization/reserved.jsonl',R9/'data/recipe-v2/optimization/excluded-sources.jsonl',R9/'remediation/continuation-step005900/reserved.jsonl',R9/'remediation/heldout-languages/language-expanded-manifest.jsonl',R9/'remediation/validation-appendix/manifest.jsonl',R9/'remediation/expressive/fresh-dev-v2.jsonl']
 for path in reserved:
  pin(path)
  for row in lines(path):block(row)
 canonical=Path('/tmp/fast-audiovae-recovery-20260909/canonical-panel-v1/source-inventory.json');pin(canonical)
 for row in read(canonical)['sources']:
  if row.get('manifest_row'):block(row['manifest_row'])
 roots=[R9/'data/recipe-v2/optimization',R9/'remediation/expressive']
 ready0=read(pin(roots[0]/'ready.json'));ready1=read(pin(roots[1]/'ready-v2.json'))
 counts=read(pin(roots[0]/'input-sample-counts.json',ready0['files_sha256']['input-sample-counts.json']))
 catalogs=[pin(roots[0]/'train-manifest.jsonl',ready0['files_sha256']['train-manifest.jsonl']),pin(roots[1]/'train-candidates-v2.jsonl',ready1['accepted_files']['train-candidates-v2.jsonl']['sha256'])]
 candidates={};rejected=Counter()
 for path in catalogs:
  for row in lines(path):
   if row['split']!='train' or any(row[k] in blocked[k] for k in KEYS):rejected['reserved_or_used']+=1;continue
   ManifestRow.from_dict(row)
   if row['duration_seconds']*48000<4096:rejected['too_short']+=1;continue
   if row['source_id'] in candidates and candidates[row['source_id']]!=row:raise ValueError('Conflicting source metadata')
   candidates[row['source_id']]=row
 # The one corrected cache is authenticated before its unused sources are reused.
 cache=Path(original['cache_path']);pin(cache,original['cache_sha256'])
 receipt_path=Path(original['overlay_receipt_path']);pin(receipt_path,original['overlay_receipt_sha256'])
 old= torch.load(cache,map_location='cpu',weights_only=True,mmap=True)
 if old['contract']!=read(receipt_path)['contract']:raise ValueError('Corrected cache contract changed')
 data=read(pin(Path(original['data_path']),original['data_sha256']))
 cached=defaultdict(list)
 for index,crop in enumerate(old['pools'][original['pool']]):
  sid=crop['source_id']
  if sid not in candidates:continue
  if any(candidates[sid][k]!=data['rows'][sid][k] for k in KEYS):raise ValueError('Cached source identity differs')
  cached[sid].append((index,crop))
 used={k:set() for k in KEYS};selected=[]
 def add(row,phase,reason,cached_entry=None):
  if any(row[k] in used[k] or row[k] in blocked[k] for k in KEYS):raise ValueError('Repeated or reserved identity')
  for k in KEYS:used[k].add(row[k])
  sid=row['source_id'];n=counts.get(sid,round(row['duration_seconds']*16000))
  if abs(n/16000-row['duration_seconds'])>1/16000+1e-10:raise ValueError('Source duration/count mismatch')
  if cached_entry:
   index,crop=cached_entry
   geometry={k:crop[k] for k in ('start_frame','context_start_frame','context_frames','scored_frames','valid_scored_samples')}
  else:
   latest=max(0,(n-40960)//640)
   start=0 if latest<30 or int(rank(sid+'/startup')[:8],16)%3==0 else 30+int(rank(sid+'/crop')[:8],16)%(latest-29)
   valid=min(40960,n-start*640)*3
   geometry={'start_frame':start,'context_start_frame':max(0,start-30),'context_frames':min(30,start),'scored_frames':math.ceil(valid/1920),'valid_scored_samples':valid}
  selected.append({'source_id':sid,'manifest_row':row,'input_samples16k':n,**geometry,'condition':None,
    'phase':phase,'selection_reason':reason,'normalized_language':row['language'].split('_')[0],
    'broad_expressive_source':row['dataset'] not in ('librispeech','fleurs','indicvoices'),
    'cached_pool_index':cached_entry[0] if cached_entry else None})
 # Breadth first within the finite unused cache, then deterministic filling.
 seed_order=sorted(cached,key=lambda sid:rank('cached/'+sid));seen_languages=set();seed=[]
 for sid in seed_order:
  language=candidates[sid]['language'].split('_')[0]
  if language not in seen_languages:seed.append(sid);seen_languages.add(language)
 seed += [sid for sid in seed_order if sid not in set(seed)]
 for sid in seed[:300]:
  best=min(cached[sid],key=lambda x:(-x[1]['valid_scored_samples'],rank(sid+'/'+str(x[0]))))
  add(candidates[sid],'approved','unused_authenticated_cached_source',best)
 if len(selected)!=300:raise ValueError('Not enough eligible corrected-cache sources to seed one shard')
 weights=original['summaries']['fit']['normalized_language_counts']
 for phase,size,cohort in (('approved',12000,0),('conditional_reserve',15000,1)):
  phase_start=0 if phase=='approved' else 12000
  groups=defaultdict(list)
  for sid,row in candidates.items():
   if any(row[k] in used[k] for k in KEYS) or int(rank('cohort/'+sid)[0],16)%2!=cohort:continue
   groups[row['language'].split('_')[0]].append(row)
  # Preserve rare explicit vocal datasets before a large generic 'und' pool
  # can crowd them out. Cohorts keep both future phases source-disjoint.
  for row in sorted((r for rows in groups.values() for r in rows
      if r['dataset'].startswith(('fsd50k_vocal_','freesound_human_whistle_'))),key=lambda r:rank('explicit/'+r['source_id'])):
   add(row,phase,'explicit_vocal_dataset_coverage')
  groups={lang:[row for row in rows if not any(row[k] in used[k] for k in KEYS)] for lang,rows in groups.items()}
  groups={lang:deque(sorted(rows,key=lambda r:rank('order/'+r['source_id']))) for lang,rows in groups.items()}
  seen=Counter(r['normalized_language'] for r in selected[phase_start:])
  heap=[((seen[lang]+1)/max(1,weights.get(lang,10)),lang) for lang,rows in groups.items() if rows];heapq.heapify(heap)
  while len(selected)-phase_start<size:
   if not heap:raise ValueError('Insufficient fresh phase capacity')
   _,lang=heapq.heappop(heap)
   row=groups[lang].popleft()
   if not any(row[k] in used[k] for k in KEYS):
    add(row,phase,'prior_language_weighted_unique_source');seen[lang]+=1
   if groups[lang]:heapq.heappush(heap,((seen[lang]+1)/max(1,weights.get(lang,10)),lang))
  ordering_start=300 if phase=='approved' else phase_start
  selected[ordering_start:]=sorted(selected[ordering_start:],key=lambda r:rank('phase-interleave/'+r['source_id']))
 if len(selected)!=27000:raise AssertionError('Wrong plan size')
 for row in selected:
  if not Path(row['manifest_row']['audio_path']).is_file():raise FileNotFoundError(row['manifest_row']['audio_path'])
 summaries={}
 for name,a,b in [('approved',0,12000),('conditional_reserve',12000,27000)]:
  rows=selected[a:b]
  summaries[name]={'sources':len(rows),'scored_seconds':sum(r['valid_scored_samples'] for r in rows)/48000,'full_source_hours':sum(r['input_samples16k'] for r in rows)/16000/3600,'languages':dict(sorted(Counter(r['normalized_language'] for r in rows).items())),'datasets':dict(Counter(r['manifest_row']['dataset'] for r in rows)),'broad_expressive_scored_percent':100*sum(r['valid_scored_samples'] for r in rows if r['broad_expressive_source'])/sum(r['valid_scored_samples'] for r in rows),'startup_sources':sum(r['start_frame']==0 for r in rows)}
 plan={'version':VERSION,'original_manifest_sha256':base.sha(original_path),'original_manifest_path':str(original_path),
       'teacher_source_sha256':base.SOURCE_SHA256,'teacher_checkpoint_sha256':base.CHECKPOINT_SHA256,
       'source_ids':[r['source_id'] for r in selected],'rows':selected,'shard_size':300,
       'approved_range':[0,12000],'conditional_reserve_range':[12000,27000],
       'source_ids_sha256':digest([r['source_id'] for r in selected]),'inputs_sha256':inputs,
       'blocked_identities':{k:sorted(v) for k,v in blocked.items()},'disjointness':{'source_id':True,'audio_sha256':True,'parent_recording_id':True,'speaker_disjointness_claimed':False},
       'summaries':summaries,'generator_sha256':base.sha(__file__),'seed':SEED,
       'source_audio_validation':'Cached seed already authenticated under original full-source contract; new sources must pass file hash, native prepared format and sample count in producer before a shard is sealed',
       'expressive_limit':'Broad expressive datasets are reported separately; no claim that arbitrary crops contain timestamp-verified laugh/cry/whistle events'}
 plan['identity_sha256']=digest(plan)
 args.out.parent.mkdir(parents=True,exist_ok=True);base.write_json(args.out,plan)
 args.shards.mkdir(parents=True)
 directory=args.shards/'000000-000300';directory.mkdir()
 crops=[]
 for row in selected[:300]:
  crop=old['pools'][original['pool']][row['cached_pool_index']]
  if crop['source_id']!=row['source_id']:raise ValueError('Seed source index changed')
  crops.append({k:v.clone() if isinstance(v,torch.Tensor) else v for k,v in crop.items()})
 payload={'format':PAIR_VERSION,'plan_identity_sha256':plan['identity_sha256'],'start_index':0,'stop_index':300,'crops':crops}
 path=directory/'pairs.pt';torch.save(payload,path)
 shard_receipt={'format':PAIR_VERSION,'complete':True,'plan_identity_sha256':plan['identity_sha256'],
    'start_index':0,'stop_index':300,'source_ids':plan['source_ids'][:300],'source_ids_sha256':digest(plan['source_ids'][:300]),
    'pairs_path':str(path),'pairs_sha256':base.sha(path),'teacher_source_sha256':base.SOURCE_SHA256,'teacher_checkpoint_sha256':base.CHECKPOINT_SHA256,
    'origin':'Exact copies from authenticated corrected full-source singleton cache',
    'original_cache_path':str(cache),'original_cache_sha256':original['cache_sha256'],
    'original_receipt_path':str(receipt_path),'original_receipt_sha256':original['overlay_receipt_sha256'],
    'encoder_policy':'Frozen FP32 raw_mu, full source singleton with cuDNN disabled',
    'decoder_policy':'Frozen FP32 full source singleton original48k decoder before cropping',
    'generator_sha256':base.sha(__file__),'parameter_updates':0}
 base.write_json(directory/'receipt.json',shard_receipt)
 base.write_json(args.out.with_name('plan-summary.json'),{'identity_sha256':plan['identity_sha256'],'plan_sha256':base.sha(args.out),'source_ids_sha256':plan['source_ids_sha256'],'summaries':summaries,'cached_eligible_sources':len(cached),'first_shard_receipt':str(directory/'receipt.json'),'first_shard_sha256':shard_receipt['pairs_sha256']})
 print(json.dumps({'plan':str(args.out),'identity_sha256':plan['identity_sha256'],'first_shard':str(directory/'receipt.json'),'summaries':summaries}),flush=True)

if __name__=='__main__':main()
